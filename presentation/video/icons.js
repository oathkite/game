// アイコンを (x, y) を中心に、1 ドット size px で描く。
export function icon(ctx, name, x, y, size, { color = '#33ff66', light = '#ffffff', alpha = 1 } = {}) {
  const rows = ICONS[name];
  if (!rows || alpha <= 0) return;
  ctx.save();
  ctx.globalAlpha = alpha;
  const left = Math.round(x - (rows[0].length * size) / 2);
  const top = Math.round(y - (rows.length * size) / 2);
  rows.forEach((row, r) => {
    for (let c = 0; c < row.length; c += 1) {
      if (row[c] === '.') continue;
      ctx.fillStyle = row[c] === '+' ? light : row[c] === '=' ? '#9aa39f' : color;
      ctx.fillRect(left + c * size, top + r * size, size, size);
    }
  });
  ctx.restore();
}
